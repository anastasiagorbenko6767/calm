const LLM_API_URL = process.env.LLM_API_URL || "https://api.groq.com/openai/v1/chat/completions";
const LLM_API_KEY = process.env.GROQ_API_KEY || process.env.OPENAI_API_KEY || process.env.LLM_API_KEY || "";
const LLM_MODEL   = process.env.LLM_MODEL   || "llama-3.3-70b-versatile";

function formatResults(results) {
  if (!Array.isArray(results) || results.length === 0) return "";
  const latest = results.slice(0, 8).map((r) => {
    const date = r.createdAt ? new Date(r.createdAt).toLocaleDateString("ru-RU") : "";
    const score = typeof r.score === "number" ? ` ${r.score}/${r.maxScore || "?"}` : "";
    const level = r.level ? ` (${r.level})` : "";
    return `• ${r.slug}:${score}${level}${date ? " — " + date : ""}`;
  });
  return `\n\nРЕЗУЛЬТАТЫ ТЕСТОВ пользователя (последние):\n${latest.join("\n")}`;
}

// ---------- режим 1: внешний LLM ----------
async function askLLM(userMessage, history, results) {
  const sys = SYSTEM_PROMPT + "\n\n" + SCALES_PRIMER + formatResults(results);
  const messages = [
    { role: "system", content: sys },
    ...history.slice(-14).map((m) => ({
      role: m.role === "ai" ? "assistant" : "user",
      content: String(m.text || "").slice(0, 2000),
    })),
    { role: "user", content: userMessage.slice(0, 2000) },
  ];
  const res = await fetch(LLM_API_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${LLM_API_KEY}`,
    },
    body: JSON.stringify({
      model: LLM_MODEL,
      messages,
      max_tokens: 380,
      temperature: 0.35,
      top_p: 0.85,
      // штраф за повторы и сваливание в прежние токены
      frequency_penalty: 0.4,
      presence_penalty: 0.2,
      // стоп-токены Qwen/Llama: как только модель их генерирует — обрезаем
      stop: ["<|im_start|>", "<|im_end|>", "<|endoftext|>", "<|user|>", "<|assistant|>", "<s>", "</s>"],
    }),
  });
  if (!res.ok) {
    const txt = await res.text().catch(() => "");
    throw new Error(`LLM ${res.status}: ${txt.slice(0, 200)}`);
  }
  const data = await res.json();
  const raw = data?.choices?.[0]?.message?.content?.trim();
  if (!raw) throw new Error("пустой ответ модели");
  return sanitize(raw);
}

// Пост-фильтр: удаляет служебные токены, CJK-символы и прочий мусор
function sanitize(text) {
  let t = text;
  // служебные chat-template теги
  t = t.replace(/<\|[a-z_]+\|>/gi, "");
  t = t.replace(/\[\/?(?:INST|SYS)\]/gi, "");
  t = t.replace(/<<\/?SYS>>/gi, "");
  t = t.replace(/<\/?s>/gi, "");
  // любые китайские/японские/корейские символы и их знаки препинания
  t = t.replace(/[　-〿぀-ヿㇰ-ㇿ㐀-䶿一-鿿가-힯＀-￯]/g, "");
  // лишние пробелы, переносы, пустые скобки «()»
  t = t.replace(/\(\s*\)/g, "");
  t = t.replace(/[ \t]+\n/g, "\n");
  t = t.replace(/\n{3,}/g, "\n\n");
  t = t.replace(/[ \t]{2,}/g, " ");
  return t.trim();
}

