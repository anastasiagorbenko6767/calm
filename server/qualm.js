const DEFAULT_REPLIES = [
  `Расскажи чуть подробнее — что ты сейчас чувствуешь в теле и в голове? Я постараюсь помочь мягко.`,
  `Я тебя слышу. Опиши ситуацию — я задам пару вопросов, чтобы лучше понять.`,
  `Хочешь — попробуй описать одним словом, как себя чувствуешь сегодня? С этого проще начать.`,
];

function askOffline(userMessage, history) {
  const text = String(userMessage || "").trim();
  if (!text) return GREETINGS[0];

  // Если это первое сообщение и оно короткое — поприветствуем
  if (history.length === 0 && text.length < 40) {
    const hi = TOPICS.find((t) => t.key === "hi");
    if (hi.match.test(text)) return hi.answer();
  }

  // Ищем тему
  for (const topic of TOPICS) {
    if (topic.match.test(text)) return topic.answer();
  }

  // ничего не распознали — отвечаем общими словами
  return DEFAULT_REPLIES[history.length % DEFAULT_REPLIES.length];
}

// ---------- точка входа ----------
export async function askQualm({ message, history = [], results = [] }) {
  const safeHistory = Array.isArray(history) ? history.slice(-20) : [];

  if (LLM_API_KEY) {
    try {
      const reply = await askLLM(message, safeHistory, results);
      return { reply, mode: "llm" };
    } catch (err) {
      // если LLM упал — не роняем диалог, уходим в offline
      console.warn("[qualm] LLM упал, отвечаю offline:", err.message);
    }
  }

  const reply = askOffline(message, safeHistory);
  return { reply, mode: "offline" };
}

export function qualmStatus() {
  return {
    name: "Квалм",
    online: !!LLM_API_KEY,
    model: LLM_API_KEY ? LLM_MODEL : "offline-rules",
  };
}
